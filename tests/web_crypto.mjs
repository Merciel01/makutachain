import assert from 'node:assert/strict';
import {createWallet,unlockWallet,signTransfer,canonical,validateVault} from '../web/wallet.mjs';
const password='Mot-de-passe-test-2026';
const alice=await createWallet('Alice',password),bob=await createWallet('Bob',password);
assert.equal(alice.name,'Alice');
assert.equal(alice.address.length,68);
assert.equal(alice.ciphertext===bob.ciphertext,false);
assert.equal('privateKey' in alice,false);
assert.equal(canonical({b:1,a:'é'}),'{"a":"é","b":1}');
const restored=JSON.parse(JSON.stringify(alice));
const aliceKey=await unlockWallet(restored,password);
assert.equal(aliceKey.extractable,false);
const tx=await signTransfer(restored,aliceKey,bob.address,4,1);
await assert.rejects(unlockWallet(alice,'mauvais-mot-de-passe'),/incorrect/);
await assert.rejects(unlockWallet({...alice,name:'Falsifié'},password),/incorrect/);
const changed=(alice.ciphertext[0]==='0'?'1':'0')+alice.ciphertext.slice(1);
await assert.rejects(unlockWallet({...alice,ciphertext:changed},password),/incorrect/);
assert.throws(()=>validateVault({...alice,network:'other'}));
assert.throws(()=>validateVault({...alice,privateKey:'untrusted'}));
await assert.rejects(createWallet('Alice','court'),/12/);
await assert.rejects(signTransfer(alice,aliceKey,bob.address,1.5,1));
await assert.rejects(signTransfer(alice,aliceKey,alice.address,1,1));
const bobKey=await unlockWallet(bob,password);
await assert.rejects(signTransfer(alice,bobKey,bob.address,1,1),/correspond/);
console.log(JSON.stringify({tx,bob:bob.address}));
